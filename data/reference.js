// The stakes page's opening headline: sector name, stakes level, and a
// one-line reason, combined into one fixed, code-assembled string, e.g.
// "HEALTHCARE SECTOR - HIGH STAKE. You handle sensitive data." or, for a
// standard-tier sector, "RETAIL SECTOR. You handle everyday customer
// data." (no "- HIGH STAKE" flag). Entirely fixed content: sector.label
// and sector.stakesReason are both pre-written, so this is never asked
// of the model, the same reasoning as everything else in this file.
function buildStakesHeadline(sector) {
  const flag = sector.stakesTier === "higher" ? " - HIGH STAKE" : "";
  return `${sector.label.toUpperCase()} SECTOR${flag}. ${sector.stakesReason}`;
}

// Builds the flat recommendation list: one entry per question the SME
// answered "no" to, in question order, nothing for questions answered
// "yes", and no grouping of any kind above the individual question.
// Each entry carries the original question text (so it's traceable back
// to exactly what was asked) plus its fixed recommendation text and
// citation. Used by api/score-assessment.js, the one place scoring
// happens: pure rule-based lookup against fixed data, answers[q.id] ===
// true or not, nothing else decides what appears here. If every
// question was answered "yes", this returns an empty array, and the
// caller shows ALL_MET_MESSAGE instead.
function buildRecommendations(answers) {
  return ASSESSMENT_QUESTIONS.filter((q) => !(answers && answers[q.id] === true)).map(
    (q) => ({
      questionId: q.id,
      question: q.text,
      text: QUESTION_RECOMMENDATIONS[q.id].text,
      citation: QUESTION_RECOMMENDATIONS[q.id].citation,
    })
  );
}

function getSector(sectorId) {
  return SECTORS.find((s) => s.id === sectorId) || null;
}

